import * as fs from 'node:fs';
import * as fsp from 'node:fs/promises';
import * as path from 'node:path';

import {
  compileWorldToGameSeed,
  type CompileWorldOptions,
  type WorldGameSeed,
  type WorldSpec,
} from '@opengame/world-spec';

export const WORLD_SEED_FILE = 'WORLD_SEED.json';

/** On-disk shape of `public/WORLD_SEED.json` (seed + application record). */
export interface WorldSeedRecord extends WorldGameSeed {
  /** True when this run prefilled `public/game.json` from the seed. */
  readonly gamePrefilled: boolean;
  readonly writtenFiles: readonly string[];
}

export interface WorldGameSeedPhaseResult {
  readonly applied: boolean;
  readonly gamePrefilled: boolean;
  readonly reason: string | null;
  readonly seed: WorldGameSeed | null;
  readonly files: readonly string[];
}

const SKIPPED = (reason: string): WorldGameSeedPhaseResult => ({
  applied: false,
  gamePrefilled: false,
  reason,
  seed: null,
  files: [],
});

function seedDisabled(): boolean {
  const raw = process.env['PLATFORM_WORLD_SEED']?.trim().toLowerCase();
  return raw === 'false' || raw === '0' || raw === 'off';
}

/** Iterations keep the polished game; only fresh generations get prefilled. */
function shouldPrefillGame(isIteration: boolean): boolean {
  if (!isIteration) return true;
  const raw = process.env['PLATFORM_WORLD_SEED_PREFILL_ON_ITERATION']
    ?.trim()
    .toLowerCase();
  return raw === 'true' || raw === '1';
}

async function readJsonIfPresent(
  file: string,
): Promise<Record<string, unknown> | null> {
  if (!fs.existsSync(file)) return null;
  try {
    const raw = JSON.parse(await fsp.readFile(file, 'utf8')) as unknown;
    if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
    return raw as Record<string, unknown>;
  } catch {
    return null;
  }
}

function renderWorldSeedModule(seed: WorldGameSeed): string {
  const scenes = seed.scenePlan.map((plan) => ({
    sceneId: plan.sceneId,
    regionId: plan.regionId,
    title: plan.title,
    kind: plan.kind,
    isStart: plan.isStart,
    grid: { cols: plan.gridCols, rows: plan.gridRows, cell: plan.cellSize },
    origin: { x: plan.originX, y: plan.originY },
    exits: plan.exits.map((exit) => ({
      portalId: exit.portalId,
      toSceneId: exit.toSceneId,
      label: exit.label,
    })),
  }));
  return `/**
 * GENERATED by worldGameSeedPhase — do not hand-edit.
 *
 * Compiled from World Spec "${seed.worldTitle}" (v${seed.worldVersion}).
 * Import these constants instead of re-typing ids so gameplay code stays in
 * lockstep with the world (\`public/WORLD_SEED.json\` holds the full seed).
 */

export const WORLD_ID = ${JSON.stringify(seed.worldId)} as const;
export const WORLD_TITLE = ${JSON.stringify(seed.worldTitle)} as const;
export const INITIAL_SCENE_ID = ${JSON.stringify(seed.lineage.initialSceneId)} as const;

export const WORLD_SCENES = ${JSON.stringify(scenes, null, 2)} as const;

export const WORLD_REGION_IDS = ${JSON.stringify(seed.lineage.regionIds)} as const;
export const WORLD_ENTITY_IDS = ${JSON.stringify(seed.lineage.entityIds)} as const;
export const WORLD_QUEST_IDS = ${JSON.stringify(seed.lineage.questIds)} as const;
export const WORLD_RULE_IDS = ${JSON.stringify(seed.lineage.ruleIds)} as const;
export const WORLD_PORTAL_IDS = ${JSON.stringify(seed.lineage.portalIds)} as const;

/** Difficulty knobs the compiler baked into game.json (L2 tunables when present). */
export const WORLD_TUNABLES = ${JSON.stringify(seed.tunables, null, 2)} as const;

export type WorldSceneId = (typeof WORLD_SCENES)[number]['sceneId'];
`;
}

/**
 * Compiles the world into `public/game.json` + `public/WORLD_SEED.json` +
 * `src/world/worldSeed.ts`. Returns what changed so callers can report it on
 * the timeline.
 */
export async function runWorldGameSeedPhase(options: {
  readonly workspace: string;
  readonly world: WorldSpec;
  readonly isIteration: boolean;
  readonly compile?: CompileWorldOptions;
}): Promise<WorldGameSeedPhaseResult> {
  const { workspace, world, isIteration } = options;
  if (seedDisabled()) return SKIPPED('PLATFORM_WORLD_SEED=false');
  if (!fs.existsSync(workspace)) return SKIPPED('workspace missing');

  let seed: WorldGameSeed;
  try {
    seed = compileWorldToGameSeed(world, options.compile);
  } catch (err) {
    return SKIPPED(
      `compile failed: ${err instanceof Error ? err.message : String(err)}`,
    );
  }
  if (seed.game.scenes.length === 0) return SKIPPED('world has no regions');

  const publicDir = path.join(workspace, 'public');
  await fsp.mkdir(publicDir, { recursive: true });
  const files: string[] = [];

  const gamePath = path.join(publicDir, 'game.json');
  const prefill = shouldPrefillGame(isIteration);
  if (prefill) {
    // Assets / audio are owned by the MiniMax phase — never drop them.
    const existing = await readJsonIfPresent(gamePath);
    const merged: Record<string, unknown> = {
      ...seed.game,
      worldStartRegionId: seed.lineage.initialSceneId,
      ...(Array.isArray(existing?.['assets']) ? { assets: existing!['assets'] } : {}),
      ...(Array.isArray(existing?.['audioTracks'])
        ? { audioTracks: existing!['audioTracks'] }
        : {}),
    };
    await fsp.writeFile(gamePath, `${JSON.stringify(merged, null, 2)}\n`, 'utf8');
    files.push('public/game.json');

    // Dual-track merge: engine customModule shells + layoutOnly region entities.
    try {
      const { healExtraScenesGameJsonWiring } = await import(
        './gameQualityArchetype.js'
      );
      const wire = await healExtraScenesGameJsonWiring(workspace, {
        worldStartRegionId: seed.lineage.initialSceneId,
      });
      if (wire.healed) {
        files.push('public/game.json#engine-world-merge');
      }
    } catch {
      /* main.ts may not exist yet on bare seed — smoke-time heal retries */
    }
  }

  const record: WorldSeedRecord = {
    ...seed,
    gamePrefilled: prefill,
    writtenFiles: files,
  };
  await fsp.writeFile(
    path.join(publicDir, WORLD_SEED_FILE),
    `${JSON.stringify(record, null, 2)}\n`,
    'utf8',
  );
  files.push(`public/${WORLD_SEED_FILE}`);

  const worldDir = path.join(workspace, 'src', 'world');
  await fsp.mkdir(worldDir, { recursive: true });
  await fsp.writeFile(
    path.join(worldDir, 'worldSeed.ts'),
    renderWorldSeedModule(seed),
    'utf8',
  );
  files.push('src/world/worldSeed.ts');

  return {
    applied: true,
    gamePrefilled: prefill,
    reason: null,
    seed,
    files,
  };
}

export async function readWorldSeedRecord(
  workspace: string,
): Promise<WorldSeedRecord | null> {
  for (const rel of [
    path.join('public', WORLD_SEED_FILE),
    path.join('dist', WORLD_SEED_FILE),
  ]) {
    const raw = await readJsonIfPresent(path.join(workspace, rel));
    if (!raw) continue;
    if (raw['schema'] !== 'opengame.world-game-seed/1') continue;
    return raw as unknown as WorldSeedRecord;
  }
  return null;
}

/**
 * Coder guidance: the structure already exists on disk, so the Agent's job
 * shrinks from "invent a game" to "add feel and depth" — which is what makes
 * the CLI pass shorter and stops it from rewriting the world away.
 */
export function formatWorldSeedForCoder(seed: WorldGameSeed): string {
  const scenes = seed.scenePlan
    .map((plan) => {
      const exits =
        plan.exits.length > 0
          ? ` → 出口 ${plan.exits.map((e) => `${e.portalId}:${e.toSceneId}`).join(' / ')}`
          : '';
      return `  - ${plan.sceneId}${plan.isStart ? '（起始区域）' : ''} = 区域「${plan.title}」${plan.gridCols}×${plan.gridRows}${exits}`;
    })
    .join('\n');
  const quests =
    seed.lineage.questIds.length > 0
      ? seed.lineage.questIds.join(', ')
      : '(无)';
  const lines = [
    '【世界编译结果 / World-compiled structure — 双层 SSOT，禁止拆掉】',
    `- 来源世界：${seed.worldTitle} (v${seed.worldVersion})，${seed.stats.regions} 区域 / ${seed.stats.entities} 实体 / ${seed.stats.quests} 任务 / ${seed.stats.portals} 传送点`,
    '- **开机层**：`TitleScene` / `ChapterScene` / `WorldScene` / `EndingScene`（以 main.ts extraScenes 为准）带 `customModule`；`initialSceneId` 必须是 Title 壳。',
    '- **区域层**：`scenes[]` 中 `layoutOnly: true` 的区域行（entities / portals）是 WorldScene 布局 SSOT；`worldStartRegionId` 为起始区域 id。',
    '- `src/world/worldSeed.ts` 导出区域 / 实体 / 任务 / 规则 ID — 写玩法时 import，不要另造 ID。',
    `- 区域清单（layoutOnly scenes[].id 必须保留，可改文案不可改名/删除）：\n${scenes}`,
    `- 任务 ID（必须保留在 game.json，可扩展文案）：${quests}`,
    `- 世界规则已映射为 ${seed.lineage.ruleIds.length} 条 manual 技能：在 Scene 里用 \`skillChain.fire(entity, '<ruleId>')\` 触发，别删这些 id。`,
    '- **禁止**：删掉 customModule 开机壳；把 initialSceneId 改回区域 id；删区域 layout 行或清空 entities；把区域「升格」成无 WorldScene 的纯 DSL 开机。',
    '- **你的任务是增量补写**：手感（tween/粒子/音效）、战斗反馈、任务 UI、失败重开；换区走 worldRegionId + WorldScene.restart（或已有 portal 接线）。',
    `- 难度参数来自 ${seed.tunablesSource ?? '默认档'}：${Object.entries(seed.tunables)
      .map(([k, v]) => `${k}=${v}`)
      .join(', ')} — 需要调难度就改这些值，别硬编码。`,
    `- 美术锚点：${seed.assetBrief.stylePrompt}（与世界同一视觉语义）`,
  ];
  return lines.join('\n');
}

/**
 * RPG / top_down prompts without a project World Spec still get a town seed
 * so WorldScene has portals/NPCs instead of an empty wander loop.
 */
export async function tryAutoRpgWorldSeed(options: {
  readonly workspace: string;
  readonly archetype: string | null | undefined;
  readonly userPrompt: string;
  readonly isIteration: boolean;
  readonly hasProjectWorld: boolean;
}): Promise<WorldGameSeedPhaseResult | null> {
  if (options.hasProjectWorld) return null;
  if (options.isIteration) return null;
  if (options.archetype !== 'top_down') return null;
  const autoOff =
    process.env['PLATFORM_AUTO_RPG_WORLD_SEED']?.trim().toLowerCase();
  if (autoOff === 'false' || autoOff === '0' || autoOff === 'off') return null;

  const { createEmptyTownWorld } = await import('@opengame/world-spec');
  const title = options.userPrompt.trim().slice(0, 48) || 'RPG town';
  const world = createEmptyTownWorld({
    id: `auto_rpg_${Date.now().toString(36)}`,
    title,
  });
  return runWorldGameSeedPhase({
    workspace: options.workspace,
    world,
    isIteration: false,
  });
}
