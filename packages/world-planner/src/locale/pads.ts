export function societyPadsFor(
  profile: { readonly id: string },
  ascii: boolean,
): readonly SocietyPad[] | undefined {
  if (profile.id === 'society.crew') return ascii ? CREW_EN_PADS : CREW_ZH_PADS;
  if (profile.id === 'society.cloister') {
    return ascii ? CLOISTER_EN_PADS : CLOISTER_ZH_PADS;
  }
  if (ascii) return TOWN_EN_PADS;
  return undefined;
}

